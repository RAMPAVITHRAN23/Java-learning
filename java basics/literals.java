// Literals are literally the values we assign to a data type. They are meant to be taken as they are.
public class literals { // Class name matches the filename (literals.java)
    public static void main(String[] args) {
        int num = 0x10; // Hexadecimal literal (0x10 = 16 in decimal)
        System.out.println(num); // Output: 16
    }
}
